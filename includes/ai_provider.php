<?php
// ============================================================================
// AI PROVIDER LAYER
//
// The one place in DFMIS that knows a specific vendor exists. Everything above
// it — the veterinary assistant, the context builder, the UI, the API — talks
// to DfmsAiProvider and cannot name a vendor even by accident.
//
// WHY THIS EXISTS
// Before Phase 5D, includes/ai_service.php curled api.anthropic.com directly
// from the middle of the tenant-accounting logic. That worked, but it meant a
// second provider could only be added by editing the function every feature
// calls. The interface moves that decision to one file.
//
// WHY ONLY ONE PROVIDER IS IMPLEMENTED
// Anthropic is the provider this deployment is configured for
// (ANTHROPIC_API_KEY, already in config/database.php and .env.example). Adding
// a second implementation nobody has credentials for would ship dead code that
// no test can exercise end to end. The interface is the deliverable; a new
// provider is a new file implementing it, with no change anywhere else.
//
// ---------------------------------------------------------------------------
// CREDENTIAL HANDLING — the rules this file enforces
//
//   1. The key is read from the environment ONLY, through the constant
//      config/database.php defines. It is never a parameter, never stored,
//      never defaulted to a literal.
//   2. No method ever RETURNS the key, or any structure containing it.
//   3. Nothing is logged except a machine token and an HTTP status. The
//      upstream response body is never logged, because a provider that echoes
//      a request header into an error message would otherwise put the key in
//      our log file.
//   4. Exceptions are not allowed to escape carrying request context. Every
//      failure becomes a reason CODE.
//   5. isConfigured() answers a boolean. It is the only thing any caller may
//      learn about credentials.
// ---------------------------------------------------------------------------
// ============================================================================

require_once __DIR__ . '/../config/database.php';
// Phase 5E. The two files reference each other deliberately: configuration
// describes how a provider is called, and the provider is what a configuration
// summary reports on. The cycle is inert — neither file runs code at include
// time that needs the other's declarations.
require_once __DIR__ . '/ai_config.php';

// ===========================================================================
// PHASE 5F — THE INTERNAL MESSAGE VOCABULARY
//
// Before this phase a message's `content` was a plain string. Tool use cannot
// be expressed that way: an assistant turn that requests a tool and the user
// turn that answers it are STRUCTURED, and flattening them to prose would mean
// the model could no longer tell its own tool request from a quotation of one.
//
// So `content` is now EITHER a string (every pre-existing caller, unchanged)
// OR a list of blocks drawn from the three types below.
//
// WHY WE DEFINE OUR OWN BLOCK VOCABULARY RATHER THAN PASSING THE VENDOR'S
// The orchestration layer (includes/ai_agent.php) has to build an assistant
// turn containing a tool request and a user turn containing its result. If it
// built those in a vendor's wire format, that format would be spread across
// the agent loop, the veterinary domain and every test — and a second provider
// would mean editing all of them. These three shapes are OURS. Translating
// them to a vendor's wire format is the provider's job and happens in exactly
// one method per provider.
//
//   text         ['type' => 'text', 'text' => string]
//   tool_use     ['type' => 'tool_use', 'id' => string, 'name' => string,
//                 'input' => array]
//   tool_result  ['type' => 'tool_result', 'tool_use_id' => string,
//                 'content' => string, 'is_error' => bool]
//
// `tool_use.id` correlates a request with its result. It is generated by the
// provider (or by us, for a provider that does not supply one) and is opaque
// everywhere else.
// ===========================================================================

// ---------------------------------------------------------------------------
// PHASE 7 — A FOURTH BLOCK TYPE: image
//
//   image        ['type' => 'image', 'media_type' => string, 'data' => string]
//
// `data` is the raw image bytes encoded as BASE64; `media_type` is a MIME type
// from the storage layer's own allow-list. Nothing vendor-specific appears in
// it, which is the whole point: Anthropic wants a nested `source` object and
// Gemini wants `inline_data`, and neither shape may leak into the domain
// module, the controller, the database or the UI.
//
// ADDED THE SAME WAY TOOL USE WAS — additively, with NO new abstract method.
// An image is just another block in a user turn, so every existing provider,
// every test double and every text-only caller is untouched. A provider that
// does not understand the block DROPS it, which is what wireBlocks() and
// wireParts() already do with anything unrecognised: the request degrades to
// a text-only one rather than being rejected by the vendor.
//
// WHAT MUST NEVER HAPPEN TO `data`
// It is never logged, never audited, never written to the database and never
// echoed in an error. It is the largest and least interesting value in the
// system, and one log line carrying a few megabytes of base64 is how a disk
// fills up. The bytes live in ONE place — the file storage layer — and this
// block is the only other copy that ever exists, for the duration of one
// request.
// ---------------------------------------------------------------------------

const DFMS_AI_BLOCK_TEXT        = 'text';
const DFMS_AI_BLOCK_TOOL_USE    = 'tool_use';
const DFMS_AI_BLOCK_TOOL_RESULT = 'tool_result';
const DFMS_AI_BLOCK_IMAGE       = 'image';

/**
 * Why the model stopped, normalised to a closed set.
 *
 * A vendor's own vocabulary never leaves its provider class. 'other' exists so
 * an unrecognised value degrades to "treat this as a finished answer" rather
 * than to an undefined branch.
 */
const DFMS_AI_STOP_REASONS = ['end_turn', 'tool_use', 'max_tokens', 'other'];

/**
 * A completion backend.
 *
 * Implementations must satisfy the credential rules above. The interface is
 * deliberately narrow: multi-turn completion and nothing else. Streaming and
 * embeddings are still not in scope.
 *
 * PHASE 5F — TOOL USE WAS ADDED WITHOUT A NEW ABSTRACT METHOD.
 *
 * Tool use is expressed through the EXISTING complete(): an optional `tools`
 * entry in $options, and three optional keys in the returned array. That is
 * deliberate. Adding a fifth abstract method would have broken every existing
 * implementation of this interface — including the provider stubs the Phase
 * 5D and 5E suites depend on to test failure paths without a network — and a
 * phase that starts by breaking the tests that prove the previous phase works
 * has chosen the wrong seam.
 *
 * A provider that ignores `tools` and returns none is CORRECT and degrades to
 * exactly the Phase 5D behaviour: the orchestration reads a missing
 * `tool_requests` as "this is a final answer".
 */
interface DfmsAiProvider
{
    /** Short stable token for logging and the ai_usage row, e.g. 'anthropic'. */
    public function name(): string;

    /** True when this provider has usable credentials. Never reveals them. */
    public function isConfigured(): bool;

    /** The model this provider will use unless overridden. */
    public function defaultModel(): string;

    /**
     * Run a multi-turn completion.
     *
     * @param string $systemPrompt  the safety and role contract
     * @param list<array{role: string, content: string|list<array<string, mixed>>}> $messages
     *        Alternating conversation turns, oldest first, ending with 'user'.
     *        `content` is prose, or a list of blocks in the internal
     *        vocabulary documented above.
     * @param array $options
     *        ['max_tokens' => int, 'model' => string, 'temperature' => float,
     *         'tools' => list<array{name: string, description: string,
     *                               input_schema: array<string, mixed>}>]
     *        `tools` is a HINT to the model and nothing more. It never
     *        authorises anything: includes/ai_tools.php re-validates the name,
     *        the arguments and the caller's permission on every execution,
     *        and a model may name a tool it was never offered.
     *
     * @return array{ok: bool, text: ?string, reason: ?string, model: string,
     *               input_tokens: int, output_tokens: int,
     *               stop_reason?: string,
     *               tool_requests?: list<array{id: string, name: string, input: array<string, mixed>}>,
     *               blocks?: list<array<string, mixed>>}
     *         `reason` is a MACHINE TOKEN on failure, never upstream prose.
     *
     *         The last three keys are PHASE 5F and OPTIONAL. An implementation
     *         that omits them is a valid provider with no tool support.
     *           stop_reason    one of DFMS_AI_STOP_REASONS
     *           tool_requests  what the model asked to run, normalised
     *           blocks         the assistant turn in the INTERNAL vocabulary,
     *                          so the orchestration can replay it verbatim on
     *                          the next round without knowing a wire format
     */
    public function complete(string $systemPrompt, array $messages, array $options = []): array;
}

// ---------------------------------------------------------------------------
// Failure reason tokens. A closed set, so the UI can map each to safe text and
// an unrecognised value can never be rendered to a user verbatim.
// ---------------------------------------------------------------------------
const DFMS_AI_FAILURE_REASONS = [
    'not_configured'     => 'The AI service is not configured on this installation.',
    'no_tenant'          => 'No active farm context.',
    'plan_limit_reached' => 'This organization has used its AI allowance for the month.',
    'empty_prompt'       => 'There was nothing to send.',
    'request_failed'     => 'The AI service could not be reached.',
    'rate_limited'       => 'The AI service is busy. Try again shortly.',
    'upstream_error'     => 'The AI service returned an error.',
    'empty_response'     => 'The AI service returned no content.',
    'transport_error'    => 'The AI service could not be reached.',

    // ---- Phase 5E ---------------------------------------------------------
    // Split out of 'upstream_error' so the retry policy can tell a transient
    // server-side failure (worth another attempt) from a request the provider
    // rejected as malformed (retrying identical bytes cannot help).
    'invalid_request'    => 'The AI service rejected the request.',
    // OUR limiter, not the provider's. Distinct from 'rate_limited' because
    // the two mean different things to the person reading the message and to
    // whoever is diagnosing it later: one is a busy vendor, the other is this
    // installation refusing to spend more on a shared allowance right now.
    'ai_rate_limited'    => 'Too many AI requests just now. Wait a moment and try again.',
];

/** Safe, user-facing text for a failure token. Never echoes an upstream body. */
function dfms_ai_failure_message(?string $reason): string {
    return DFMS_AI_FAILURE_REASONS[$reason ?? '']
        ?? 'The AI service is unavailable right now.';
}

// ===========================================================================
// ANTHROPIC
// ===========================================================================

final class DfmsAnthropicProvider implements DfmsAiProvider
{
    private string $model;
    private int $timeoutSeconds;

    public function __construct(string $model = 'claude-sonnet-5', int $timeoutSeconds = 60)
    {
        $this->model = $model;
        $this->timeoutSeconds = $timeoutSeconds;
    }

    public function name(): string
    {
        return 'anthropic';
    }

    /**
     * Credentials are read here and nowhere else in the class, so there is
     * exactly one expression in the codebase that evaluates to the key.
     */
    private function apiKey(): string
    {
        return defined('ANTHROPIC_API_KEY') ? (string) ANTHROPIC_API_KEY : '';
    }

    public function isConfigured(): bool
    {
        return $this->apiKey() !== '';
    }

    public function defaultModel(): string
    {
        return $this->model;
    }

    public function complete(string $systemPrompt, array $messages, array $options = []): array
    {
        $model = (string) ($options['model'] ?? $this->model);
        $fail = static function (string $reason) use ($model): array {
            return [
                'ok' => false, 'text' => null, 'reason' => $reason,
                'model' => $model, 'input_tokens' => 0, 'output_tokens' => 0,
            ];
        };

        if (!$this->isConfigured()) {
            return $fail('not_configured');
        }

        $normalised = self::toWireMessages($messages);
        if ($normalised === []) {
            return $fail('empty_prompt');
        }

        $payload = [
            'model'      => $model,
            'max_tokens' => (int) ($options['max_tokens'] ?? 1024),
            'system'     => $systemPrompt,
            'messages'   => $normalised,
        ];
        if (isset($options['temperature'])) {
            $payload['temperature'] = (float) $options['temperature'];
        }

        // Phase 5F. Tool definitions are sent only when the caller offers some,
        // so a request with no tools produces byte-for-byte the Phase 5D
        // payload. The vendor's key happens to be named `tools` as well; the
        // mapping is still done here rather than assumed, because the shape
        // arriving from includes/ai_tools.php is OURS.
        $tools = $options['tools'] ?? [];
        if (is_array($tools) && $tools !== []) {
            $payload['tools'] = array_values(array_map(
                static function (array $tool): array {
                    return [
                        'name'         => (string) $tool['name'],
                        'description'  => (string) $tool['description'],
                        'input_schema' => $tool['input_schema'],
                    ];
                },
                $tools
            ));
        }

        $body = json_encode($payload, JSON_UNESCAPED_UNICODE);
        if ($body === false) {
            return $fail('empty_prompt');
        }

        $ch = curl_init('https://api.anthropic.com/v1/messages');
        if ($ch === false) {
            return $fail('transport_error');
        }

        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT        => $this->timeoutSeconds,
            CURLOPT_CONNECTTIMEOUT => 10,
            CURLOPT_HTTPHEADER     => [
                'content-type: application/json',
                'x-api-key: ' . $this->apiKey(),
                'anthropic-version: 2023-06-01',
            ],
            CURLOPT_POSTFIELDS => $body,
        ]);

        $raw = curl_exec($ch);
        $httpCode = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $transportError = curl_errno($ch) !== 0;
        curl_close($ch);

        if ($raw === false || $transportError) {
            // Deliberately does NOT log curl_error(): it can contain the
            // request URL and, on some builds, header context.
            error_log('[' . dfms_ai_request_ref() . '] ai provider anthropic: transport failure');
            return $fail('transport_error');
        }

        if ($httpCode !== 200) {
            // Status code only. The upstream body is NEVER logged — a provider
            // that echoes a request header into its error text would otherwise
            // write our API key into this log line.
            error_log('[' . dfms_ai_request_ref() . "] ai provider anthropic: HTTP $httpCode");
            if ($httpCode === 429) {
                return $fail('rate_limited');
            }
            if ($httpCode === 401 || $httpCode === 403) {
                return $fail('not_configured');
            }
            // Phase 5E: 4xx is OUR mistake, 5xx is theirs, and only the latter
            // is worth retrying. Collapsing both into 'upstream_error' meant a
            // rejected request would be sent again, unchanged, to be rejected
            // again — burning the provider's patience proving nothing.
            return $fail($httpCode >= 400 && $httpCode < 500 ? 'invalid_request' : 'upstream_error');
        }

        $decoded = json_decode((string) $raw, true);
        if (!is_array($decoded)) {
            return $fail('empty_response');
        }

        $parsed = self::readResponse($decoded);
        $text = $parsed['text'];

        // A turn carrying tool requests and NO prose is a perfectly good
        // response — it is the normal shape of "I need to look something up".
        // Only a turn with neither prose nor a tool request is empty.
        if (($text === null || trim($text) === '') && $parsed['tool_requests'] === []) {
            return $fail('empty_response');
        }

        return [
            'ok'            => true,
            'text'          => $text,
            'reason'        => null,
            'model'         => $model,
            'input_tokens'  => (int) ($decoded['usage']['input_tokens'] ?? 0),
            'output_tokens' => (int) ($decoded['usage']['output_tokens'] ?? 0),
            // Phase 5F, all three in the INTERNAL vocabulary. Nothing below
            // this line ever sees an Anthropic-shaped structure.
            'stop_reason'   => $parsed['stop_reason'],
            'tool_requests' => $parsed['tool_requests'],
            'blocks'        => $parsed['blocks'],
        ];
    }

    /**
     * Translate a vendor response envelope into the internal vocabulary.
     *
     * PUBLIC AND STATIC ON PURPOSE. This is one half of the vendor mapping
     * seam (toWireMessages() is the other), and it is the half most likely to
     * be wrong: it reads a structure we do not control, defensively, and every
     * branch in it is a guess about what a vendor might send. A mapping that
     * can only be reached by making a live, authenticated HTTP call is a
     * mapping that is never exercised by the test suite — which is exactly how
     * the Phase 5D bug this method fixes survived unnoticed.
     *
     * THAT BUG: the old inline loop kept `text` blocks and SILENTLY DISCARDED
     * everything else. A `tool_use` block therefore vanished, left the text
     * null, and the call reported 'empty_response' — a real answer surfaced to
     * the user as an outage, with nothing recording that a block was dropped.
     *
     * @param array<string, mixed> $decoded  the vendor's decoded JSON body
     * @return array{text: ?string, blocks: list<array<string, mixed>>,
     *               tool_requests: list<array{id: string, name: string, input: array<string, mixed>}>,
     *               stop_reason: string}
     */
    public static function readResponse(array $decoded): array
    {
        $text = null;
        $blocks = [];
        $toolRequests = [];

        $content = $decoded['content'] ?? [];
        if (!is_array($content)) {
            $content = [];
        }

        foreach ($content as $block) {
            if (!is_array($block)) {
                continue;
            }
            $type = (string) ($block['type'] ?? DFMS_AI_BLOCK_TEXT);

            if ($type === DFMS_AI_BLOCK_TEXT && isset($block['text'])) {
                $text = ($text ?? '') . (string) $block['text'];
                $blocks[] = ['type' => DFMS_AI_BLOCK_TEXT, 'text' => (string) $block['text']];
                continue;
            }

            if ($type === DFMS_AI_BLOCK_TOOL_USE) {
                // A malformed tool block is DROPPED, not guessed at. Inventing
                // a name or an id here would put a fabricated tool call into
                // the orchestration, and the loop would faithfully refuse
                // something the model never asked for.
                $name = isset($block['name']) && is_string($block['name']) ? $block['name'] : '';
                $id   = isset($block['id']) && is_string($block['id']) ? $block['id'] : '';
                if ($name === '' || $id === '') {
                    error_log('[' . dfms_ai_request_ref()
                        . '] ai provider anthropic: discarded a malformed tool_use block');
                    continue;
                }
                // Arguments arrive as whatever the model produced. They are
                // carried through UNVALIDATED and untrusted; ai_tools.php
                // validates them against the tool's own schema before any
                // domain function is reached.
                $input = isset($block['input']) && is_array($block['input']) ? $block['input'] : [];

                $toolRequests[] = ['id' => $id, 'name' => $name, 'input' => $input];
                $blocks[] = [
                    'type'  => DFMS_AI_BLOCK_TOOL_USE,
                    'id'    => $id,
                    'name'  => $name,
                    'input' => $input,
                ];
            }
            // Any other block type is ignored. This provider asks for none.
        }

        return [
            'text'          => $text,
            'blocks'        => $blocks,
            'tool_requests' => $toolRequests,
            'stop_reason'   => self::normaliseStopReason($decoded['stop_reason'] ?? null),
        ];
    }

    /**
     * Map the vendor's finish reason onto DFMS_AI_STOP_REASONS.
     *
     * An unrecognised value becomes 'other', which the orchestration treats as
     * "the model is finished". That is the safe default: the alternative —
     * treating an unknown reason as "keep going" — would let a vendor add a
     * value tomorrow and turn our bounded loop into a longer one.
     */
    private static function normaliseStopReason($raw): string
    {
        if (!is_string($raw)) {
            return 'other';
        }
        switch ($raw) {
            case 'end_turn':
            case 'stop_sequence':
                return 'end_turn';
            case 'tool_use':
                return 'tool_use';
            case 'max_tokens':
                return 'max_tokens';
            default:
                return 'other';
        }
    }

    /**
     * Coerce turns into the provider's expected wire shape.
     *
     * PUBLIC AND STATIC ON PURPOSE — the outbound half of the vendor mapping
     * seam, testable for the same reason readResponse() is. A tool exchange
     * that is mis-serialised here is rejected by the vendor with a 400, which
     * this codebase reports as 'invalid_request' and does not retry; without a
     * direct test the first sign of a mistake would be an assistant that
     * silently stops working the moment a tool is involved.
     *
     * Consecutive same-role turns are merged and empty ones dropped, because a
     * conversation loaded from the database can legitimately contain a
     * degraded assistant turn that carries no usable content.
     *
     * PHASE 5F — BLOCK TURNS ARE NOT TEXT AND ARE NOT TREATED AS TEXT.
     *
     * A block turn is never trimmed, never string-concatenated and never
     * coerced. Two same-role block turns merge by APPENDING THEIR BLOCK LISTS,
     * and a string turn adjacent to a block turn is promoted to a text block
     * first — joining them with "\n\n" would produce a turn whose tool request
     * had been stringified into prose, and the vendor would reject it (or,
     * worse, the model would read its own protocol as something a human said).
     *
     * @param list<array{role: string, content: string|list<array<string, mixed>>}> $messages
     * @return list<array{role: string, content: string|list<array<string, mixed>>}>
     */
    public static function toWireMessages(array $messages): array
    {
        $clean = [];
        foreach ($messages as $message) {
            $role = ($message['role'] ?? '') === 'assistant' ? 'assistant' : 'user';
            $raw = $message['content'] ?? '';

            if (is_array($raw)) {
                $blocks = self::wireBlocks($raw);
                if ($blocks === []) {
                    continue;   // nothing survived translation
                }
                $last = count($clean) - 1;
                if ($last >= 0 && $clean[$last]['role'] === $role) {
                    $clean[$last]['content'] = array_merge(
                        self::asBlockList($clean[$last]['content']),
                        $blocks
                    );
                    continue;
                }
                $clean[] = ['role' => $role, 'content' => $blocks];
                continue;
            }

            $content = trim((string) $raw);
            if ($content === '') {
                continue;
            }
            $last = count($clean) - 1;
            if ($last >= 0 && $clean[$last]['role'] === $role) {
                if (is_array($clean[$last]['content'])) {
                    $clean[$last]['content'][] = ['type' => 'text', 'text' => $content];
                } else {
                    $clean[$last]['content'] .= "\n\n" . $content;
                }
                continue;
            }
            $clean[] = ['role' => $role, 'content' => $content];
        }

        // The provider requires the exchange to begin with a user turn.
        while ($clean !== [] && $clean[0]['role'] !== 'user') {
            array_shift($clean);
        }
        return $clean;
    }

    /**
     * Promote a turn's content to a block list, whatever it currently is.
     *
     * @param string|list<array<string, mixed>> $content
     * @return list<array<string, mixed>>
     */
    private static function asBlockList($content): array
    {
        return is_array($content) ? $content : [['type' => 'text', 'text' => (string) $content]];
    }

    /**
     * Translate INTERNAL blocks into this vendor's wire format.
     *
     * The one place in the codebase where the internal vocabulary meets an
     * Anthropic-shaped structure. An unrecognised block is DROPPED rather than
     * passed through: forwarding a block this provider does not understand
     * would mean sending the vendor something no one here has reasoned about.
     *
     * @param array<int|string, mixed> $blocks
     * @return list<array<string, mixed>>
     */
    private static function wireBlocks(array $blocks): array
    {
        $wire = [];
        foreach ($blocks as $block) {
            if (!is_array($block)) {
                continue;
            }
            switch ((string) ($block['type'] ?? '')) {
                case DFMS_AI_BLOCK_TEXT:
                    $text = trim((string) ($block['text'] ?? ''));
                    if ($text !== '') {
                        $wire[] = ['type' => 'text', 'text' => $text];
                    }
                    break;

                case DFMS_AI_BLOCK_TOOL_USE:
                    $wire[] = [
                        'type'  => 'tool_use',
                        'id'    => (string) ($block['id'] ?? ''),
                        'name'  => (string) ($block['name'] ?? ''),
                        // An empty argument set must serialise as {} and not
                        // as [], which is what json_encode does with an empty
                        // PHP array — and the vendor rejects a list here.
                        'input' => (object) (is_array($block['input'] ?? null) ? $block['input'] : []),
                    ];
                    break;

                case DFMS_AI_BLOCK_TOOL_RESULT:
                    $result = [
                        'type'        => 'tool_result',
                        'tool_use_id' => (string) ($block['tool_use_id'] ?? ''),
                        'content'     => (string) ($block['content'] ?? ''),
                    ];
                    if (!empty($block['is_error'])) {
                        $result['is_error'] = true;
                    }
                    $wire[] = $result;
                    break;

                // Phase 7. The internal block carries a media type and base64
                // bytes; this vendor wants them nested under a `source` object
                // with a `type` naming the encoding. That nesting exists only
                // here — includes/ai_vision.php has never heard of it.
                //
                // A block with no data is DROPPED rather than sent empty: an
                // image part the vendor rejects fails the whole request with a
                // 400, which this codebase does not retry, so the model would
                // simply stop answering the moment a photo was involved.
                case DFMS_AI_BLOCK_IMAGE:
                    $data = (string) ($block['data'] ?? '');
                    $mediaType = (string) ($block['media_type'] ?? '');
                    if ($data === '' || $mediaType === '') {
                        break;
                    }
                    $wire[] = [
                        'type'   => 'image',
                        'source' => [
                            'type'       => 'base64',
                            'media_type' => $mediaType,
                            'data'       => $data,
                        ],
                    ];
                    break;
            }
        }
        return $wire;
    }
}

